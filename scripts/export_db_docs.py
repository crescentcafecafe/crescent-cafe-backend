"""Generate docs/DATABASE.md (tables, columns, foreign keys, constraints, indexes) from the SQLAlchemy models.   python -m scripts.export_db_docs"""
import os

os.environ.setdefault("DATABASE_URL", "sqlite+aiosqlite:///./_doc.db")
import app.models  # noqa: F401,E402
from app.db.base import Base  # noqa: E402
from sqlalchemy import Index, UniqueConstraint  # noqa: E402

GROUPS = [
    ("Identity & access", ["branches", "admin_users", "customers", "riders", "refresh_tokens", "devices", "fcm_tokens"]),
    ("Dine-in", ["tables", "table_qr_tokens", "table_sessions"]),
    ("Menu", ["menu_categories", "menu_items", "menu_item_variants", "menu_addons"]),
    ("Orders", ["orders", "order_items", "order_item_customizations", "order_status_history"]),
    ("Payments", ["payments", "payment_webhook_events", "refunds"]),
    ("Delivery", ["rider_assignments", "rider_locations", "delivery_otps"]),
    ("Chat", ["conversations", "conversation_members", "messages", "message_read_receipts"]),
    ("Notifications & jobs", ["notification_events", "notification_delivery_logs", "jobs"]),
    ("Offers", ["offers", "coupons", "coupon_redemptions"]),
    ("Settings, invoices, audit", ["cafe_settings", "tax_settings", "delivery_settings", "invoices", "invoice_items", "audit_logs"]),
]
INTRO = """# Database design (PostgreSQL / Supabase)

Generated by `python -m scripts.export_db_docs` from the models in `app/models/`; the Alembic migration in `migrations/versions/` is verified against the models in CI (`alembic check`).

## Conventions
* UUID primary keys (`gen` in Python); `BIGINT identity` for append-only logs (`order_status_history`, `notification_events`, `messages`, `rider_locations`, `audit_logs`).
* **Money is integer paise** (never floats). Tax rates are basis points (500 = 5.00 %).
* All timestamps are `timestamptz` (UTC). Reports convert to the cafe time zone.
* **Multi-branch ready:** `branch_id` is on every branch-scoped table (menu, tables, orders, payments, riders, settings, offers (nullable = all branches), invoices). No code path hard-codes a branch id: the default branch is resolved at request time (`X-Branch-Code` header later).
* Snapshots: orders/invoices copy names, prices, tax and table label, so later menu edits never rewrite history.

## Key relationships
```
branches 1─* admin_users | riders | tables | menu_categories | menu_items | orders | payments | invoices | tax_settings
branches 1─1 cafe_settings, delivery_settings
customers 1─* orders (nullable: guest orders carry only a hashed guest token)
tables 1─* table_qr_tokens (exactly one ACTIVE per table)      tables 1─* table_sessions (at most one OPEN per table)
table_sessions 1─* orders        (many customers at one table => many separate orders, one session)
menu_categories 1─* menu_items 1─* menu_item_variants | menu_addons
orders 1─* order_items 1─* order_item_customizations ; orders 1─* order_status_history (permanent event log)
orders 1─* payments 1─* refunds ; payments *─* payment_webhook_events (by gateway order id, unique per gateway+event)
orders 1─* rider_assignments *─1 riders (at most one ACTIVE assignment per order)
orders 1─* delivery_otps (at most one ACTIVE otp per order; only a keyed hash is stored)
rider_assignments 1─* rider_locations
offers 1─* coupons ; offers 1─* coupon_redemptions *─1 orders
conversations 1─* conversation_members | messages 1─* message_read_receipts ; conversations *─1 customers|riders, optional orders
devices 1─* fcm_tokens ; notification_events 1─* notification_delivery_logs
orders 1─1 invoices 1─* invoice_items
```

## Integrity rules enforced by the database (not just by code)
| Rule | Mechanism |
|---|---|
| Only one primary Admin can ever exist | partial unique index `uq_admin_single_primary` |
| One active QR token per table; old token can never resolve | partial unique index on `table_qr_tokens(table_id) WHERE status='active'` + hash lookup |
| One open session per table | partial unique index on `table_sessions(table_id) WHERE status='open'` |
| Table numbers unique among non-archived tables | partial unique index |
| No duplicate orders on retries | unique `(idem_scope, idempotency_key)` |
| One active rider assignment per order | partial unique index on `rider_assignments(order_id)` |
| One active delivery OTP per order | partial unique index on `delivery_otps(order_id)` |
| Duplicate webhooks ignored | unique `(gateway, event_id)` |
| No duplicate gateway references | unique `(gateway, gateway_order_id)` and `(gateway, gateway_payment_id)` |
| A coupon cannot be redeemed twice for one order | unique `(offer_id, order_id)` ; limits re-checked under `SELECT … FOR UPDATE` on the offer row |
| Invoice numbers unique | unique `(branch_id, invoice_number)` ; sequence allocated under a row lock on `cafe_settings` |
| Coupon codes unique | unique `code` |
| Positive money amounts | `CHECK (amount_paise > 0)`, `CHECK (price_paise >= 0)`, `CHECK (rate_bps BETWEEN 0 AND 10000)` |
| Background job de-duplication | unique `jobs.idempotency_key` ; notification de-dupe unique `notification_events.dedupe_key` |

## Hot-path indexes
`orders(branch_id,status,created_at)`, `orders(customer_id,created_at)`, `orders(table_session_id)`, `orders(customer_phone)`, `payments(status,method)`, `payments(gateway,gateway_order_id)`,
`rider_assignments(rider_id,status)`, `rider_locations(order_id,recorded_at)`, `coupon_redemptions(offer_id,status)`, `coupon_redemptions(offer_id,redeemer_key)`, `messages(conversation_id,id)`,
`conversation_members(role,user_id)`, `devices(owner_role,owner_id,install_id)` (unique), `fcm_tokens(token)` (unique), `jobs(status,run_at)`, `audit_logs(entity_type,entity_id)`.

"""


def main() -> None:
    t = Base.metadata.tables
    out = [INTRO, "## Tables\n"]
    seen = set()
    for title, names in GROUPS:
        out.append(f"### {title}\n")
        for n in names:
            seen.add(n)
            tb = t[n]
            out.append(f"#### `{n}`\n\n| Column | Type | Null | Notes |\n|---|---|---|---|")
            for c in tb.columns:
                notes = []
                if c.primary_key: notes.append("PK")
                for fk in c.foreign_keys: notes.append(f"FK → {fk.column.table.name}.{fk.column.name}" + (f" ON DELETE {fk.ondelete}" if fk.ondelete else ""))
                if c.unique: notes.append("unique")
                cls = c.type.__class__.__name__
                typ = "uuid" if cls == "Uuid" else "jsonb" if cls in ("JSON", "JSONB") else "timestamptz" if cls == "UTCDateTime" else str(c.type).split("(")[0] if not getattr(c.type, "length", None) else str(c.type)
                out.append(f"| `{c.name}` | {typ} | {'yes' if c.nullable else 'no'} | {', '.join(notes)} |")
            extra = []
            for cons in tb.constraints:
                if isinstance(cons, UniqueConstraint) and len(cons.columns) > 1:
                    extra.append(f"unique({', '.join(c.name for c in cons.columns)})")
            for ix in tb.indexes:
                where = ix.dialect_options["postgresql"].get("where")
                extra.append(("unique " if ix.unique else "") + f"index({', '.join(c.name for c in ix.columns)})" + (f" WHERE {where}" if where is not None else ""))
            if extra:
                out.append("\nConstraints / indexes: " + "; ".join(extra))
            out.append("")
    missing = set(t) - seen
    assert not missing, missing
    os.makedirs("docs", exist_ok=True)
    open("docs/DATABASE.md", "w").write("\n".join(out))
    print("wrote docs/DATABASE.md", len(t), "tables")


if __name__ == "__main__":
    main()
