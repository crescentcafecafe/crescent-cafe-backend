from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import Boolean, ForeignKey, Index, Integer, String, Text, Uuid, text
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, Created, Updated, UUIDPk


class Branch(Base):
    __tablename__ = "branches"
    id: Mapped[UUIDPk]
    code: Mapped[str] = mapped_column(String(32), unique=True)
    name: Mapped[str] = mapped_column(String(120))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[Created]


class AdminUser(Base):
    __tablename__ = "admin_users"
    id: Mapped[UUIDPk]
    branch_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("branches.id"), index=True)
    email: Mapped[str] = mapped_column(String(255), unique=True)
    name: Mapped[str] = mapped_column(String(120))
    password_hash: Mapped[str] = mapped_column(String(255))
    is_primary: Mapped[bool] = mapped_column(Boolean, default=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    last_login_at: Mapped[datetime | None]
    failed_logins: Mapped[int] = mapped_column(Integer, default=0)
    locked_until: Mapped[datetime | None]
    created_at: Mapped[Created]
    updated_at: Mapped[Updated]
    __table_args__ = (
        # exactly one primary admin can exist (enforced by the database)
        Index("uq_admin_single_primary", "is_primary", unique=True, postgresql_where=text("is_primary"), sqlite_where=text("is_primary")),
    )


class Customer(Base):
    __tablename__ = "customers"
    id: Mapped[UUIDPk]
    email: Mapped[str | None] = mapped_column(String(255), unique=True)
    google_sub: Mapped[str | None] = mapped_column(String(64), unique=True)
    password_hash: Mapped[str | None] = mapped_column(String(255))
    name: Mapped[str] = mapped_column(String(120))
    phone: Mapped[str | None] = mapped_column(String(20), index=True)  # E.164, required before ordering
    avatar_url: Mapped[str | None] = mapped_column(String(500))
    marketing_opt_in: Mapped[bool] = mapped_column(Boolean, default=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    anonymized_at: Mapped[datetime | None]
    created_at: Mapped[Created]
    updated_at: Mapped[Updated]


class Rider(Base):
    __tablename__ = "riders"
    id: Mapped[UUIDPk]
    branch_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("branches.id"), index=True)
    name: Mapped[str] = mapped_column(String(120))
    phone: Mapped[str] = mapped_column(String(20), unique=True)
    email: Mapped[str | None] = mapped_column(String(255))
    password_hash: Mapped[str] = mapped_column(String(255))
    vehicle_info: Mapped[str | None] = mapped_column(String(120))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    is_available: Mapped[bool] = mapped_column(Boolean, default=False)
    must_change_password: Mapped[bool] = mapped_column(Boolean, default=False)
    failed_logins: Mapped[int] = mapped_column(Integer, default=0)
    locked_until: Mapped[datetime | None]
    created_at: Mapped[Created]
    updated_at: Mapped[Updated]


class AuthSession(Base):
    """Refresh-token session. One row per login; refresh tokens rotate and reuse revokes the session."""

    __tablename__ = "refresh_tokens"
    id: Mapped[UUIDPk]
    role: Mapped[str] = mapped_column(String(16))  # admin | customer | rider
    user_id: Mapped[uuid.UUID] = mapped_column(Uuid)
    token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    prev_token_hash: Mapped[str | None] = mapped_column(String(64), index=True)
    device_label: Mapped[str | None] = mapped_column(String(200))
    ip: Mapped[str | None] = mapped_column(String(64))
    expires_at: Mapped[datetime]
    revoked_at: Mapped[datetime | None]
    last_used_at: Mapped[datetime | None]
    created_at: Mapped[Created]
    __table_args__ = (Index("ix_sessions_user", "role", "user_id"),)


class Device(Base):
    __tablename__ = "devices"
    id: Mapped[UUIDPk]
    owner_role: Mapped[str] = mapped_column(String(16))
    owner_id: Mapped[uuid.UUID] = mapped_column(Uuid)
    install_id: Mapped[str] = mapped_column(String(100))  # stable per-app-install id generated by the client
    platform: Mapped[str] = mapped_column(String(20), default="android")
    device_model: Mapped[str | None] = mapped_column(String(120))
    os_version: Mapped[str | None] = mapped_column(String(40))
    app_version: Mapped[str | None] = mapped_column(String(40))
    locale: Mapped[str | None] = mapped_column(String(20))
    notifications_enabled: Mapped[bool] = mapped_column(Boolean, default=True)  # OS permission state reported by client
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    last_seen_at: Mapped[datetime | None]
    created_at: Mapped[Created]
    __table_args__ = (Index("uq_device_owner_install", "owner_role", "owner_id", "install_id", unique=True),)


class FcmToken(Base):
    __tablename__ = "fcm_tokens"
    id: Mapped[UUIDPk]
    device_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("devices.id", ondelete="CASCADE"), index=True)
    token: Mapped[str] = mapped_column(String(1024), unique=True)
    is_valid: Mapped[bool] = mapped_column(Boolean, default=True)
    last_error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[Created]
    updated_at: Mapped[Updated]
